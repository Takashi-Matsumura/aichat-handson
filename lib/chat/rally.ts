// ラリーモード: AIが一度に答えを出し切らず、問いを返しながら利用者と一緒に答えへたどり着くモード。
//
// AIが大量の回答を一度に生成すると、利用者がそれを読み流すだけになり、自分で考える機会が減る。
// そこで、短い返答＋問いかけで会話の往復(ラリー)を促し、利用者の考えを引き出す。
// 利用者が明確に答えを求めた場合は答えを示す(業務で詰まらないようにするため)が、
// その後に自分の言葉で説明してもらい、理解を確かめる。

// 小さいモデル(gemma-3-4b)でも従えるよう、ルールは少なく・短く・断定的に書く。
// 「3〜5文程度」のような幅のある書き方や「〜を確かめる」のような抽象的な指示だと、
// 前置きや原因の列挙で長くなり、答えを求められても質問を続けてしまった。
export const RALLY_SYSTEM_PROMPT = `あなたは対話の相棒です。利用者が自分で考えて答えにたどり着けるよう、短いやり取りを重ねて導きます。

# 返答のルール
- 返答は全体で3文以内にする。前置き・共感の言葉・原因や選択肢の列挙は書かない。
- 最後に、利用者に考えてもらう質問を1つだけ書く。質問を2つ以上書かない。
- 利用者が考えを述べたら、良い点を一言認め、次に考えるためのヒントを1つだけ示す。正解をすぐに言わない。
- 利用者が「答えを教えて」のように答えを求めたら、断らずに結論を2〜3文で示す。そのあと「なぜそうなるか、あなたの言葉で説明できますか？」のように、理解を確かめる質問を1つ書く。
- 利用者が答えにたどり着いたら、学んだことを自分の言葉でまとめるよう促す。`

// ラリーモードの生成トークン数の上限。プロンプトの指示を無視して長文を書くのを防ぎ、
// 会場で共有している推論サーバーの占有時間も短くする。
export const RALLY_MAX_TOKENS = 800

// このリクエストで使う生成トークン数の上限を決める。
// 推論モードでは思考過程(<think>)も同じ上限を消費するため、短くすると回答本文に届く前に
// 打ち切られてしまう。推論モードを併用するときは通常の上限のままにする。
export function resolveMaxTokens(base: number, opts: { rally: boolean; thinking: boolean }): number {
  if (!opts.rally || opts.thinking) return base
  return Math.min(base, RALLY_MAX_TOKENS)
}
